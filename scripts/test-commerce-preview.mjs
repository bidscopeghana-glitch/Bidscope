import {createRequire} from "node:module";
const {chromium}=createRequire(import.meta.url)("../outputs/browser-tools/node_modules/@playwright/test");
import assert from "node:assert/strict";
const browser=await chromium.launch({channel:"chrome",headless:true});
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 // Test only the local preview; never transmit fixture actions to external services.
 await context.route("**/*",route=>new URL(route.request().url()).hostname==="127.0.0.1"?route.continue():route.abort());
 // Exercise the sample fallback independently of any private local CJ feed.
 await context.route("**/api/commerce/local-catalogue/feed",route=>route.fulfill({json:{mode:"private_cj_preview",items:[]}}));
 const page=await context.newPage(),errors=[];
 page.on("pageerror",e=>errors.push(e.message));
 page.on("console",msg=>{if(msg.type()==="error"&&/hydration|hydrated|server rendered/i.test(msg.text()))errors.push(msg.text());});
 await page.goto("http://127.0.0.1:3012/shop");
 await page.getByRole("heading",{name:"Your everyday finds. A world of possibilities."}).waitFor();
 await page.getByRole("button",{name:"Reject optional",exact:true}).click();
 await page.evaluate(()=>document.fonts.ready);
 assert.equal(await page.evaluate(()=>document.fonts.check('14px "Amazon Ember"')),true);
 assert.equal(await page.getByRole("link",{name:"Sign in to BidScope",exact:true}).isVisible(),true);
 assert.equal(await page.getByRole("link",{name:"Sign in to BidScope",exact:true}).getAttribute("href"),"/sign-in?next=%2Fshop");
 await page.screenshot({path:process.env.COMMERCE_DESKTOP_SCREENSHOT||"outputs/commerce-desktop.png",fullPage:true});
 await page.getByRole("button",{name:"Arc desk light",exact:true}).click();
 await page.getByLabel("Quantity",{exact:true}).fill("2");
 await page.getByRole("button",{name:"Add to sample bag"}).click();
 await page.getByRole("button",{name:"Bag (2)",exact:true}).click();
 assert.equal(await page.getByRole("button",{name:"Live checkout unavailable"}).isDisabled(),true);
 await page.getByRole("button",{name:"Simulate checkout · no payment"}).click();
 await page.getByRole("heading",{name:"Your orders",exact:true}).waitFor();
 await page.getByRole("button",{name:"Sample administration"}).click();
 await page.getByRole("button",{name:"Simulate supplier payment failure"}).click();
 assert.ok((await page.locator(".shop-order").innerText()).includes("exception"));
 await page.getByRole("button",{name:"Simulate supplier payment",exact:true}).click();
 await page.getByRole("button",{name:"Simulate shipment",exact:true}).click();
 await page.getByRole("button",{name:"Simulate delivery",exact:true}).click();
 await page.getByRole("button",{name:"My orders",exact:true}).click();
 await page.getByRole("button",{name:"Request return",exact:true}).click();
 await page.getByRole("button",{name:"Sample administration"}).click();
 await page.getByRole("button",{name:"Request sample refund",exact:true}).click();
 await page.getByRole("button",{name:"Confirm sample refund",exact:true}).click();
 assert.ok((await page.locator(".shop-order").innerText()).includes("refunded"));
 await page.reload();
 await page.getByRole("button",{name:"My orders",exact:true}).click();
 await page.getByText("refunded",{exact:true}).waitFor();
 await page.getByRole("button",{name:"Discover",exact:true}).click();
 await page.getByLabel("Search products").fill("flask");
 assert.equal(await page.locator(".shop-grid article").count(),1);
 await page.getByLabel("Search products").fill("");
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:process.env.COMMERCE_MOBILE_SCREENSHOT||"outputs/commerce-mobile.png",fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),"Mobile page must not overflow horizontally");
 const signIn=page.getByRole("link",{name:"Sign in to BidScope",exact:true});
 assert.equal(await signIn.isVisible(),true);
 await signIn.click();
 await page.getByRole("heading",{name:"Welcome to BidScope",exact:true}).waitFor();
 await page.getByRole("tab",{name:"Sign in",exact:true}).waitFor();
 await page.evaluate(()=>document.fonts.ready);
 assert.equal(await page.locator('input[name="email"]').isVisible(),true);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),"Mobile sign-in must not overflow horizontally");
 await page.screenshot({path:"outputs/commerce-sign-in-mobile.png",fullPage:true});
 const checkout=await context.request.post("http://127.0.0.1:3012/api/commerce/checkout",{data:{}});
 assert.equal(checkout.status(),503);
 const account=await context.request.get("http://127.0.0.1:3012/api/commerce/account");
 assert.equal(account.status(),401);
 const admin=await context.request.get("http://127.0.0.1:3012/api/commerce/admin");
 assert.ok([401,503].includes(admin.status()));
 assert.deepEqual(errors,[]);
 console.log("PASS: desktop/mobile shopping, quantity/cart, disabled live checkout, sample order, supplier failure/recovery, tracking, return/refund, persistence, search, API boundaries. No external requests.");
}finally{await browser.close();}
